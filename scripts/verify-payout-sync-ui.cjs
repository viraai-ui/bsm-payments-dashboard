const fs = require('node:fs')
const assert = require('node:assert/strict')

const client = fs.readFileSync('src/components/PaymentsClient.tsx', 'utf8')
const css = fs.readFileSync('src/app/payments-cleanup.css', 'utf8')
const paymentsApi = fs.readFileSync('src/app/api/payments/route.ts', 'utf8')
const retryApi = fs.readFileSync('src/app/api/integrations/payouts/retry/route.ts', 'utf8')

for (const label of ['Sync Pending', 'Synced to Payouts', 'Sync Failed', 'Manual Review']) {
  assert.ok(client.includes(label), `missing payout sync label: ${label}`)
}
assert.match(client, /value === "failed" \|\| value === "manual_review"/, 'retry is limited to failed/manual-review states')
assert.match(client, /role === "Admin" && <PayoutSync/g, 'status and retry UI are admin-only')
assert.doesNotMatch(client, /role !== "Viewer" && <PayoutSync/, 'non-admin roles must not receive payout controls')
assert.match(client, /role="status" aria-live="polite"/, 'sync result is announced accessibly')
assert.match(client, /disabled=\{retrying\} aria-busy=\{retrying\}/, 'retry prevents duplicate activation and exposes busy state')
assert.match(client, /fetch\("\/api\/integrations\/payouts\/retry"/)
assert.match(client, /JSON\.stringify\(\{ eventId: sync\.eventId \}\)/)
assert.match(client, /j\.data\.payments[\s\S]*payment\.payoutSync/, 'UI consumes status from normal payments refresh')
assert.match(paymentsApi, /a\.user\.role!==\'Admin\'/, 'payments API only decorates admin responses')
assert.match(paymentsApi, /payoutSync:states\.get\(payment\.id\)/, 'payments API returns per-payment safe status')
assert.doesNotMatch(paymentsApi, /item\.(?:body|lastError)|PAYOUTS_INTEGRATION_SECRET|X-BSM-Signature/, 'payments API status must not expose payloads or delivery internals')
assert.match(retryApi, /requireUser\(\['Admin'\]\)/, 'retry API is admin-only')
assert.match(retryApi, /eventId:result\.eventId,status:result\.status,outcome:result\.outcome/, 'retry response returns the updated event')
assert.match(css, /\.payout-sync button\{[^}]*min-height:44px/, 'retry target is at least 44px tall')
assert.match(css, /\.payout-sync-badge\{[^}]*max-width:100%/, 'badge cannot overflow its container')
assert.match(css, /@media\(max-width:760px\)\{\.payment-mobile-controls\{flex-wrap:wrap\}/, 'mobile controls wrap instead of overflowing')
console.log('Payout sync UI/API/accessibility contract verified')
